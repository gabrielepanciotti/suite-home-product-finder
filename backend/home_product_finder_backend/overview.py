"""Overview endpoint — live scheda-nodo for the homeProductFinder node.

A single read-only endpoint that merges the static ``overview.manifest.json``
(generated by the ``scheda-nodo`` skill / ``suite_core.nodes node-overview``)
with a **live** ``database`` section produced by querying
``information_schema.tables`` and ``SELECT count(*)`` on every applicative
table of the node's own Postgres.

Public like ``/api/health``: this API has no auth/portal gate, and the payload
carries no secrets — only identity/functionality/DB-row-count metadata — so
other Life nodes may introspect it freely.

Graceful degradation:
- manifest missing -> minimal ``identity`` dict, ``live: false`` + ``warning``;
- ``DATABASE_URL`` unset (JSON-only mode) or DB query failing -> the
  ``database`` section carries an ``error`` field, ``live: false``, and the
  rest of the payload is served normally (always HTTP 200).
"""
from __future__ import annotations

import asyncio
import json
import logging
from pathlib import Path
from typing import Any

from fastapi import APIRouter
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from . import db

logger = logging.getLogger(__name__)

router = APIRouter(tags=["overview"])

# Repo root: backend/home_product_finder_backend/overview.py -> repo/.
_MANIFEST_PATH = Path(__file__).resolve().parents[2] / "overview.manifest.json"

# Tables that are migration infrastructure, not app data.
_EXCLUDED_TABLES: frozenset[str] = frozenset({"alembic_version"})


async def _load_manifest() -> dict[str, Any] | None:
    """Return the parsed manifest or *None* if the file does not exist."""
    if not _MANIFEST_PATH.exists():
        return None
    try:
        raw = await asyncio.to_thread(_MANIFEST_PATH.read_text, encoding="utf-8")
        return json.loads(raw)  # type: ignore[return-value]
    except Exception:
        logger.exception("overview: failed to parse manifest at %s", _MANIFEST_PATH)
        return None


async def _query_database_section(
    session: AsyncSession,
    highlight_specs: list[dict[str, str]],
) -> dict[str, Any]:
    """Return ``{"tables": [...], "highlights": [...]}`` from live DB counts.

    Table names are discovered generically via ``information_schema``; nothing
    is hard-coded. Identifiers are quoted so exotic names can't break or
    inject the count statement.
    """
    result = await session.execute(
        text(
            """
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = 'public'
              AND table_type = 'BASE TABLE'
            ORDER BY table_name
            """
        )
    )
    table_names: list[str] = [row[0] for row in result.fetchall()]

    rows: list[dict[str, Any]] = []
    counts: dict[str, int] = {}
    for tname in table_names:
        if tname in _EXCLUDED_TABLES:
            continue
        safe_name = tname.replace('"', '""')
        count_result = await session.execute(text(f'SELECT count(*) FROM "{safe_name}"'))
        count: int = count_result.scalar_one()
        rows.append({"name": tname, "rows": count})
        counts[tname] = count

    highlights = [
        {"label": spec["label"], "value": counts[spec["name"]]}
        for spec in highlight_specs
        if spec["name"] in counts
    ]
    return {"tables": rows, "highlights": highlights}


async def _build_database_section(
    highlight_specs: list[dict[str, str]],
) -> dict[str, Any]:
    """Live DB section; on any failure it degrades to an ``error`` field.

    The node's DB is optional (JSON-only mode when ``DATABASE_URL`` is unset):
    in that case the section reports ``database not configured``. Full
    tracebacks stay server-side; callers only see a generic message.
    """
    factory = db.session_factory()
    if factory is None:
        return {"tables": [], "highlights": [], "error": "database not configured"}
    try:
        async with factory() as session:
            return await _query_database_section(session, highlight_specs)
    except Exception:
        logger.exception("overview: DB section query failed")
        return {"tables": [], "highlights": [], "error": "database query failed"}


async def build_overview() -> dict[str, Any]:
    """Assemble the full scheda-nodo payload (manifest + live DB section)."""
    manifest = await _load_manifest()

    if manifest is None:
        return {
            "identity": {"slug": "homeProductFinder", "name": "HomeProductFinder"},
            "database": {"tables": [], "highlights": []},
            "live": False,
            "warning": (
                "overview.manifest.json missing — run the scheda-nodo skill "
                "(suite_core.nodes node-overview) to generate it"
            ),
        }

    # Highlight specs from the manifest map table names to display labels.
    highlight_specs: list[dict[str, str]] = []
    seen_names: set[str] = set()
    for source in (
        (manifest.get("database") or {}).get("highlights", []),
        (manifest.get("overview") or {}).get("highlights", []),
    ):
        for h in source:
            name = h.get("name") or h.get("label") or ""
            label = h.get("label") or name
            if name and name not in seen_names:
                highlight_specs.append({"name": name, "label": label})
                seen_names.add(name)

    database_section = await _build_database_section(highlight_specs)
    live = "error" not in database_section
    return {**manifest, "database": database_section, "live": live}


@router.get(
    "/api/overview",
    summary="Scheda nodo: identità, funzioni, collaborazioni, DB live, brain, pagine",
)
async def get_overview() -> dict[str, Any]:
    """Return the full node overview payload (always 200; degrades gracefully)."""
    return await build_overview()
